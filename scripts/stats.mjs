// Stats — aggregate the *imported* dataset for the landing pages, category counts and
// city pickers. There is deliberately no generator here: the app ships with no listings
// and these numbers stay at zero until real data is imported.
//
//   node scripts/stats.mjs                 # reads public/data/listings.json (or $VITE_DATA_FILE)
//   node scripts/stats.mjs --in=file.json
//   node scripts/stats.mjs --empty         # reset to zero (used when no dataset is configured)
//
// Writes src/data/stats.generated.js + public/data/listings.txt (the payload the data worker
// fetches at runtime). Both are artifacts — commit them only if you self-host the data.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATEGORY_BY_ID } from '../src/data/categories.js';
import { CITIES } from '../src/data/geo.js';
import { waNumber } from '../src/lib/whatsapp.js';
import { validPkPoint } from '../src/lib/geovalidate.js';
import { isUsableName, isPlaceholderPhone } from '../src/lib/quality.js';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const args = Object.fromEntries(
  process.argv.slice(2).map((a) => {
    const [k, ...rest] = a.replace(/^--/, '').split('=');
    return [k, rest.join('=') || true];
  })
);

const OUT_TXT = `${ROOT}/public/data/listings.txt`;
const OUT_JS = `${ROOT}/src/data/stats.generated.js`;
const OUT_CORPUS = `${ROOT}/server-data/corpus.js`;

function writeCorpus(payloadText) {
  mkdirSync(`${ROOT}/server-data`, { recursive: true });
  writeFileSync(OUT_CORPUS, 'export default ' + JSON.stringify(payloadText) + ';\n', 'utf8');
}

function writeEmpty(reason) {
  mkdirSync(`${ROOT}/public/data`, { recursive: true });
  const empty = '{"v":1,"total":0}\n';
  writeFileSync(OUT_TXT, empty, 'utf8');
  writeCorpus(empty);
  writeFileSync(OUT_JS, `// AUTO-GENERATED by scripts/stats.mjs — do not edit.
// No dataset configured${reason ? ` (${reason})` : ''}: the directory is intentionally empty until
// real listings are imported with \`npm run import\`.
export const STATS = {
  total: 0,
  generatedAt: null,
  source: 'none',
  byCat: {},
  byCity: {},
};

export const CITY_COVERAGE = [];

export const COVERAGE = {
  citiesCovered: 0,
  citiesTotal: ${CITIES.length},
  total: 0,
  whatsappCapable: 0,
  whatsappPct: 0,
  ownerVerified: 0,
  ownerVerifiedPct: 0,
  withWebsite: 0,
};

/** Shown in the UI instead of fake volume. */
export const DATASET_MODE = 'empty';
`, 'utf8');
  console.log('stats: 0 listings (empty dataset)');
}

const input = args.in || process.env.VITE_DATA_FILE || `${ROOT}/public/data/listings.json`;

if (args.empty || !existsSync(input)) {
  writeEmpty(args.empty ? 'explicit' : 'no data file');
  process.exit(0);
}

const payload = JSON.parse(readFileSync(input, 'utf8'));
let records = payload.records || payload;
if (!Array.isArray(records) || records.length === 0) {
  writeEmpty('empty file');
  process.exit(0);
}

// Last line of defence before anything is published: a record with a placeholder name or
// number, or a coordinate outside Pakistan, must never reach the runtime payload — even if
// it somehow got into the corpus file. `npm run audit -- --fix` removes them permanently
// and prints why; here they are simply not shipped.
const dropped = { foreignPin: 0, placeholderName: 0, placeholderPhone: 0 };
records = records.filter((r) => {
  if (!isUsableName(r.name)) { dropped.placeholderName++; return false; }
  if (isPlaceholderPhone(r.phone)) { dropped.placeholderPhone++; return false; }
  if ((r.lat != null || r.lng != null) && !validPkPoint(r.lat, r.lng)) { dropped.foreignPin++; return false; }
  return true;
});
if (dropped.foreignPin || dropped.placeholderName || dropped.placeholderPhone) {
  console.warn('stats: refused to publish some records:');
  if (dropped.foreignPin) console.warn(`  ${dropped.foreignPin} with a pin outside Pakistan (run: npm run audit -- --fix)`);
  if (dropped.placeholderName) console.warn(`  ${dropped.placeholderName} with a placeholder name`);
  if (dropped.placeholderPhone) console.warn(`  ${dropped.placeholderPhone} with a placeholder phone number`);
}
if (!records.length) {
  writeEmpty('every record failed the quality check');
  process.exit(0);
}

const byCat = {};
const byCity = {};
const cityIndex = new Map(CITIES.map((c, i) => [c.name, i]));
let whatsappCapable = 0;
let ownerVerified = 0;
let withWebsite = 0;
const lines = [];

records.forEach((r, i) => {
  const catId = typeof r.cat === 'object' ? r.cat.id : r.cat;
  const cat = CATEGORY_BY_ID[catId];
  const cityIdx = cityIndex.get(r.city) ?? 0;
  const seed = r.seed ?? i + 1;

  byCat[catId] = (byCat[catId] || 0) + 1;
  byCity[r.city] = (byCity[r.city] || 0) + 1;
  if (waNumber(r.phone)) whatsappCapable++;
  if (r.ownerVerified) ownerVerified++;
  if (r.website) withWebsite++;

  // Pipe format: name|catId|cityIdx|areaIdx|streetIdx|bldg|seed|id|phone|whatsapp|source|email|website|lat|lng|rating|reviews|hours|area|address|province
  const esc = (v) => (v == null ? '' : String(v).replace(/\|/g, '/').replace(/\n/g, ' '));
  lines.push([
    esc(r.name), cat ? cat.id : catId ?? 0, cityIdx, 0, 0, esc(r.area || r.city), seed,
    esc(r.id), esc(r.phone), r.whatsapp ? 1 : 0, esc(r.source || 'dataset'),
    esc(r.email), esc(r.website),
    validPkPoint(r.lat, r.lng) ? r.lat : '', validPkPoint(r.lat, r.lng) ? r.lng : '',
    r.rating ?? '', r.reviews ?? '', esc(r.hours), esc(r.area), esc(r.address), esc(r.province),
  ].join('|'));
});

const header = {
  v: 2,
  total: records.length,
  generatedAt: new Date().toISOString(),
  sources: [...new Set(records.map((r) => r.source || 'dataset'))],
  whatsappCapable,
  ownerVerified,
};
mkdirSync(`${ROOT}/public/data`, { recursive: true });
const payloadText = JSON.stringify(header) + '\n' + lines.join('\n');
writeFileSync(OUT_TXT, payloadText, 'utf8');
writeCorpus(payloadText);

// Per-city coverage — which cities actually have listings and how contactable they are.
const coveragePath = `${ROOT}/public/data/coverage.json`;
const coverageRaw = existsSync(coveragePath) ? JSON.parse(readFileSync(coveragePath, 'utf8')) : { cities: {} };
const cityStats = new Map();
for (const r of records) {
  const c = cityStats.get(r.city) || { name: r.city, total: 0, whatsappCapable: 0, ownerVerified: 0 };
  c.total++;
  if (waNumber(r.phone)) c.whatsappCapable++;
  if (r.ownerVerified) c.ownerVerified++;
  cityStats.set(r.city, c);
}
const coveredCities = [...cityStats.values()]
  .map((c) => ({ ...c, lastImportAt: coverageRaw.cities?.[c.name]?.lastImportAt || null }))
  .sort((a, b) => b.total - a.total);

writeFileSync(OUT_JS, `// AUTO-GENERATED by scripts/stats.mjs — do not edit.
export const STATS = ${JSON.stringify({
  total: records.length,
  generatedAt: header.generatedAt.slice(0, 10),
  source: header.sources.join(','),
  byCat,
  byCity,
}, null, 2)};

/** Cities that actually have listings — the honest share of Pakistan covered so far. */
export const CITY_COVERAGE = ${JSON.stringify(coveredCities, null, 2)};

export const COVERAGE = ${JSON.stringify({
  citiesCovered: coveredCities.length,
  citiesTotal: CITIES.length,
  total: records.length,
  whatsappCapable,
  whatsappPct: +((whatsappCapable / records.length) * 100).toFixed(1),
  ownerVerified,
  ownerVerifiedPct: +((ownerVerified / records.length) * 100).toFixed(1),
  withWebsite,
}, null, 2)};

/** Shown in the UI instead of fake volume. */
export const DATASET_MODE = 'imported';
`, 'utf8');

console.log(`stats: ${records.length.toLocaleString()} listings`);
console.log(`  WhatsApp-capable : ${whatsappCapable.toLocaleString()} (${((whatsappCapable / records.length) * 100).toFixed(1)}%)`);
console.log(`  owner verified   : ${ownerVerified.toLocaleString()}`);
console.log(`  → ${OUT_TXT.replace(ROOT + '/', '')}, src/data/stats.generated.js`);
